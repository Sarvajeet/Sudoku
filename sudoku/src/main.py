from .grid import SudokuGrid

def main():
    print("Welcome to Sudoku!")

    # Example Sudoku puzzle
    initial_grid = [
        [5, 3, 0, 0, 7, 0, 0, 0, 0],
        [6, 0, 0, 1, 9, 5, 0, 0, 0],
        [0, 9, 8, 0, 0, 0, 0, 6, 0],
        [8, 0, 0, 0, 6, 0, 0, 0, 3],
        [4, 0, 0, 8, 0, 3, 0, 0, 1],
        [7, 0, 0, 0, 2, 0, 0, 0, 6],
        [0, 6, 0, 0, 0, 0, 2, 8, 0],
        [0, 0, 0, 4, 1, 9, 0, 0, 5],
        [0, 0, 0, 0, 8, 0, 0, 7, 9]
    ]

    grid = SudokuGrid(initial_grid)
    print("Unsolved Sudoku:")
    print(grid)

    if grid.solve():
        print("Solved Sudoku:")
        print(grid)
    else:
        print("No solution exists.")

if __name__ == "__main__":
    main()
